static inline unsigned
ac_mgfx2_reg(bool is_xclipse940, unsigned amd_reg, enum ac_mgfx2_reg mgfx2_reg)
{
   return is_xclipse940 ? mgfx2_reg : amd_reg;
}

struct ac_mgfx2_pgm_regs {
   unsigned lo;
   unsigned hi;
   unsigned rsrc1;
   unsigned rsrc2;
};

enum ac_mgfx2_shader_stage {
   AC_MGFX2_SHADER_NGG,
   AC_MGFX2_SHADER_HULL,
};

static inline struct ac_mgfx2_pgm_regs
ac_mgfx2_shader_pgm_regs(enum ac_mgfx2_shader_stage stage)
{
   const struct ac_mgfx2_pgm_regs ngg = {
      AC_MGFX2_SPI_SHADER_PGM_LO_ES, AC_MGFX2_SPI_SHADER_PGM_HI_ES,
      AC_MGFX2_SPI_SHADER_PGM_RSRC1_GS, AC_MGFX2_SPI_SHADER_PGM_RSRC2_GS,
   };
   const struct ac_mgfx2_pgm_regs hull = {
      AC_MGFX2_SPI_SHADER_PGM_LO_LS, AC_MGFX2_SPI_SHADER_PGM_HI_LS,
      AC_MGFX2_SPI_SHADER_PGM_RSRC1_HS, AC_MGFX2_SPI_SHADER_PGM_RSRC2_HS,
   };

   assert(stage == AC_MGFX2_SHADER_NGG || stage == AC_MGFX2_SHADER_HULL);
   return stage == AC_MGFX2_SHADER_HULL ? hull : ngg;
}

